// The fake pixiv's works (design-test-harness.md "Fixtures"). Pure data plus URL builders; image and
// zip bytes are generated on demand by ./assets.ts, so no binaries are committed.

export type ImageExt = 'jpg' | 'png';

interface WorkBase {
  id: string;
  title: string;
  userName: string;
  userId: string;
  xRestrict: 0 | 1 | 2;
  /** pixiv's description HTML. */
  description: string;
  tags: readonly string[];
  /** ISO 8601 with offset, as pixiv sends it. Also gives the i.pximg.net date path. */
  createDate: string;
  /** Width and height of page 0 (illust/manga) or of every frame (ugoira). */
  width: number;
  height: number;
  /** Logged-in requests to /pages and /ugoira_meta still get `{ error: true }` (pixiv's R-18 display off). */
  r18Hidden?: boolean;
  /**
   * An all-ages work behind pixiv's sensitive-content login wall (`sl` 4): logged out, /ajax/illust
   * sends no image URLs and the page shows the wall, while /pages and /ugoira_meta still answer.
   */
  sensitiveWall?: boolean;
  /** i.pximg.net bytes of this work are sent without Content-Length (chunked). */
  noContentLength?: boolean;
  /** Every ajax endpoint answers 404 `{ error: true }`. */
  deleted?: boolean;
  /** What the fixture exists to exercise. */
  purpose: string;
}

export interface IllustWork extends WorkBase {
  illustType: 0 | 1;
  /** One entry per page, in page order. */
  pages: readonly ImageExt[];
}

export interface UgoiraWork extends WorkBase {
  illustType: 2;
  /** Per-frame delay in ms, in frame order. */
  frameDelays: readonly number[];
  /** Index of a frame whose bytes are not an image. */
  corruptFrame?: number;
}

export type Work = IllustWork | UgoiraWork;

/** Fields a spec may override at runtime with `server.patchWork()`; none of them changes generated bytes. */
export type WorkPatch = Partial<
  Pick<
    WorkBase,
    | 'title'
    | 'userName'
    | 'xRestrict'
    | 'sensitiveWall'
    | 'r18Hidden'
    | 'noContentLength'
    | 'deleted'
  >
>;

function repeat<T>(value: T, count: number): T[] {
  return new Array<T>(count).fill(value);
}

