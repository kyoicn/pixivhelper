export const PIXIV_ORIGIN = 'https://www.pixiv.net';
export const PXIMG_ORIGIN = 'https://i.pximg.net';
export const ACCOUNTS_ORIGIN = 'https://accounts.pixiv.net';
/** The only Referer i.pximg.net accepts for /img-* paths. */
export const PIXIV_REFERER = 'https://www.pixiv.net/';

export function workById(id: string): Work | undefined {
  return WORKS.find((work) => work.id === id);
}

export function requireWork(id: string): Work {
  const work = workById(id);
  if (!work) throw new Error(`no fixture work ${id}`);
  return work;
}

export function pageCount(work: Work): number {
  return work.illustType === 2 ? 1 : work.pages.length;
}

/** `2026/09/28/21/14/00`: pixiv's image date path, taken from the createDate wall-clock time. */
function datePath(work: Work): string {
  return work.createDate.slice(0, 19).replace(/[-T:]/g, '/');
}

export function artworkUrl(id: string): string {
  return `${PIXIV_ORIGIN}/artworks/${id}`;
}

export function originalUrl(work: IllustWork, page: number): string {
  return `${PXIMG_ORIGIN}/img-original/img/${datePath(work)}/${work.id}_p${page}.${work.pages[page] ?? 'jpg'}`;
}

export function masterUrl(work: Work): string {
  return `${PXIMG_ORIGIN}/img-master/img/${datePath(work)}/${work.id}_p0_master1200.jpg`;
}

/** `ugoira_meta.body.originalSrc`. */
export function ugoiraZipUrl(work: UgoiraWork): string {
  return `${PXIMG_ORIGIN}/img-zip-ugoira/img/${datePath(work)}/${work.id}_ugoira1920x1080.zip`;
}

/** `ugoira_meta.body.src` (pixiv's 600 px variant; served with the same bytes). */
export function ugoiraSmallZipUrl(work: UgoiraWork): string {
  return `${PXIMG_ORIGIN}/img-zip-ugoira/img/${datePath(work)}/${work.id}_ugoira600x600.zip`;
}

export function frameFileName(index: number): string {
  return `${String(index).padStart(6, '0')}.jpg`;
}
